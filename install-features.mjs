// ---------- small edits to existing files ----------
function patch(rel, edit) {
  if (!fs.existsSync(rel)) stop(rel + " was not found.");
  const before = fs.readFileSync(rel, "utf8");
  let after;
  try {
    after = edit(before);
  } catch (e) {
    stop("Could not edit " + rel + ": " + e.message);
  }
  if (after === null) {
    console.log("  already " + rel);
    return;
  }
  fs.writeFileSync(rel, after, "utf8");
  console.log("  edited  " + rel);
}

